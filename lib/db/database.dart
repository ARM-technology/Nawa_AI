@DriftDatabase(tables: [Sessions, Messages])
class AppDatabase extends _$AppDatabase {
  AppDatabase() : super(_openConnection());

  // Override to handle schema migrations if needed later
  @override
  int get schemaVersion => 1;

  // Factory method to open the database connection
  static Future<AppDatabase> openConnection() async {
    final dbFolder = await getApplicationDocumentsDirectory();
    final path = join(dbFolder.path, 'nowachat_database.sqlite');
    return AppDatabase(NativeDatabase.createInBackground(path));
  }

  /// Initialize and return a new instance of the database.
  static Future<AppDatabase> initialize() async {
    return await AppDatabase.openConnection();
  }


  // === SESSION CRUD Operations (Agent A Public API) ===

  /// Creates a new chat session and returns the created Session object.
  Future<Session> insertSession({String title, Int? modelId}) async {
    return await into(sessions).insert(SessionsCompanion.insert(title: title, modelId: modelId));
  }

  /// Retrieves all sessions in the database, ordered by creation date descending.
  Future<List<Session>> getAllSessions() async {
    return (select(sessions)..orderBy([(t) => OrderingTerm(expression: t.createdAt, mode: OrderingMode.desc)]))
        .get();
  }

  /// Retrieves a specific session by its ID, including all associated messages.
  Future<SessionWithMessages> getSessionWithMessages(int sessionId) async {
    // Fetch the single Session object
    final session = await (select(sessions)..where((t) => t.id.equals(sessionId))).getSingleOrNull();
    if (session == null) {
      throw StateError('Session not found.');
    }

    // Fetch messages belonging to this session, ordered chronologically.
    final messages = await (select(messages)..where((t) => t.sessionId.equals(sessionId))).get();

    return SessionWithMessages(session: session, messages: messages);
  }

  /// Updates an existing session's title and last activity timestamp.
  Future<void> updateSession({required int sessionId, String? title}) async {
    final now = DateTime.now();
    await (update(sessions)..where((t) => t.id.equals(sessionId)))
        .write(SessionsCompanion(updatedAt: Value(now), title: Value(title ?? sessions.title.get($)!)
        ));
  }

  /// Deletes a session and cascades the deletion to its associated messages (enforced by foreign key).
  Future<void> deleteSession(int sessionId) async {
    await (delete(sessions)..where((t) => t.id.equals(sessionId))).go();
  }


  // === MESSAGE CRUD Operations (Agent A Public API) ===

  /// Adds a new message to a specific session ID.
  Future<void> insertMessage({required int sessionId, required String role, required String content}) async {
    await into(messages).insert(MessagesCompanion.insert(sessionId: sessionId, role: role, content: content));
  }

  // Note: Message retrieval is handled via getSessionWithMessages().
}


